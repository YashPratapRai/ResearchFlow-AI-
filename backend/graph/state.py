from typing import TypedDict, Annotated
import operator


class ResearchState(TypedDict):

    # ============================================================
    # USER QUESTION
    # ============================================================

    question: str

    # ============================================================
    # PLANNER
    # ============================================================

    plan: dict

    research_queries: list[str]

    # ============================================================
    # RESEARCHER
    # ============================================================

    retrieved_documents: list[dict]

    research_notes: list[str]

    # ============================================================
    # WRITER
    # ============================================================

    draft_answer: str

    # ============================================================
    # CRITIC
    # ============================================================

    critique: dict

    # ============================================================
    # REVISION
    # ============================================================

    revision_request: str

    revision_count: int

    # ============================================================
    # FINAL ANSWER
    # ============================================================

    final_answer: str

    # ============================================================
    # EXECUTION HISTORY
    # ============================================================

    # operator.add means every new event is appended
    # instead of replacing the previous history.

    execution_history: Annotated[
        list[dict],
        operator.add
    ]

    # ============================================================
    # NODE COUNTS
    # ============================================================

    node_counts: dict

    # ============================================================
    # CRITIC STATISTICS
    # ============================================================

    critic_passes: int

    critic_failures: int